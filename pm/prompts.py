# ==========================================================================
# 定界符卫生：从模板自身推导出「包装标签」清单，再把外部内容里出现的同名标签转义
# ==========================================================================
_PLACEHOLDER_RE = re.compile(r"<<\w+>>")
_TAG_RE = re.compile(r"</?[A-Za-z_\u4e00-\u9fff][A-Za-z0-9_\u4e00-\u9fff]*>")

#: 不以 *_USER 结尾、但会被 render() 渲染进请求体的模板名。
#: 加新模板时若它带包装标签，必须登记到这里，否则标签得不住中和（见 _derive_wrapper_tags）。
EXTRA_RENDERED_TEMPLATES: tuple[str, ...] = ("EVALUATOR_RULES", "EVALUATOR_CHECKLIST")


def _derive_wrapper_tags() -> list[str]:
    """只扫 *_USER 模板：它们才是真正把标签渲染出去的地方。

    扫 *_SYSTEM 会把「如 <输入>…</输入>」这类**教模型怎么用标签**的说明文字
    一起当成我们的包装标签，从而把完全正常的交付物误判为泄漏。
    自动推导而非手写清单，顺带消除「清单与实际模板对不上」的死码（A8）。
    """
    names = [n for n in globals() if n.endswith("_USER")]
    # 少数模板不是 *_USER 但同样会被 render() 注入 user 段（如评估器的规则清单）：
    # 不登记进来，它里的 </RULES> 就挡不住中和，递来的数据可以提前闭合自己的包装标签。
    names += [n for n in EXTRA_RENDERED_TEMPLATES if n in globals()]
    found: list[str] = []
    for name in names:
        tpl = globals().get(name)
        if not isinstance(tpl, str):
            continue
        for ph in _PLACEHOLDER_RE.findall(tpl):
            if ph not in found:
                found.append(ph)
        for tag in _TAG_RE.findall(_PLACEHOLDER_RE.sub("", tpl)):
            if tag not in found:
                found.append(tag)
    return found


#: 渲染时真正使用的包装标签 / 占位符（prompts.sanitize_data 与 quality 检查共用）
WRAPPER_TAGS: list[str] = _derive_wrapper_tags()


def sanitize_data(text: Any) -> str:
    """把待处理数据里的包装标签中和掉（只动我们自己的标签，不碰正文里的 HTML/代码）。"""
    out = str(text)
    for tag in WRAPPER_TAGS:
        if tag in out:
            out = out.replace(tag, "&lt;" + tag[1:-1] + "&gt;")
    return out
