def rubric_stamp() -> str:
    """评委判据指纹：评分提示词一改，旧的评估缓存必须失效。

    为什么需要：评估结果缓存键含 `judge_spec`（模型）与 `extra`（需求文本），
    但不含**评委照哪份 rubric 打的分**。改了锚点/权威顺序后继续命中旧判定，
    等于拿上一版评分标准的结果汇报这一版（2026-09-18 实测到这个口子）。
    """
    digest = hashlib.sha1((EVALUATOR_SYSTEM + "\n" + EVALUATOR_RULES).encode("utf-8")).hexdigest()
    return digest[:10]


def checklist_rubric_stamp() -> str:
    """判定式协议的判据指纹。

    与 `rubric_stamp()` 分开是必须的：两套协议在同一份 (prompt, input, output) 上
    得出的结论不是同一件事，共用一个缓存键会让"换协议"命中另一套协议的结果 ——
    A/B 两种协议的复现性对比就会变成拿旧结果比旧结果。
    """
    raw = EVALUATOR_SYSTEM_CHECKLIST + "\n" + EVALUATOR_CHECKLIST
    digest = hashlib.sha1(raw.encode("utf-8")).hexdigest()
    return digest[:10]


def render(template: str, **kwargs: Any) -> str:
    """用 <<VAR>> 占位符渲染，避免 str.format 与正文 JSON 花括号冲突。

    所有外部内容都先过 `sanitize_data()`：旧版是裸 `str.replace`，被测输出里只要带一个
    `</TEST_OUTPUT>` 就能提前闭合数据区，把后续文本落到标签外（审查结论 M6：
    「XML 包裹」挡得住语义劫持，挡不住定界符越界）。
    """
    out = template
    for k, v in kwargs.items():
        out = out.replace(f"<<{k}>>", "" if v is None else sanitize_data(v))
    return out


